/** Relevans för Finance respektive Supply Chain. */
export type Relevance = "yes" | "partial" | "no";

export const RELEVANCE_LABEL: Record<Relevance, string> = {
  yes: "Ja",
  partial: "Delvis",
  no: "Nej",
};

export interface IsvSolution {
  id: string;
  name: string;
  vendor: string;
  shortDescription: string;       // 1 rad till kortet
  type: SolutionType;
  category: SolutionCategory;
  tier: SolutionTier;
  tags: string[];
  industries: SolutionIndustry[];
  geo: SolutionGeo[];
  what: string;                   // Vad lösningen är
  useCases: string[];             // Vad den används till
  whenFits: string;               // När den passar
  combos: string[];               // Vanliga kombinationer
  partnersSE: string[];           // Partners i Sverige (max 5)
  partnerSource?: string;         // Vem listar partnerskapet offentligt
  products?: string[];            // Dynamics 365-produkter lösningen är byggd för
  industryFocus?: string[];       // Svenska branscher lösningen är inriktad mot
  partnerSlugs?: string[];        // Återförsäljare/partners (slugs) angivna av ISV:n
  vendorWebsite?: string;         // Länk angiven av ISV:n
  vendorUpdatedAt?: string;       // När ISV:n senast uppdaterade texten
  // ── Utökad, produktneutral modell ────────────────────────────────
  slug?: string;                  // URL-slug (= id för databasposter)
  vendorSlug?: string;            // Koppling till leverantörsentiteten
  subcategory?: string;
  deliveryModel?: DeliveryModel;
  financeRelevance?: Relevance;
  supplyChainRelevance?: Relevance;
  // Relevans per Customer Engagement-applikation
  salesRelevance?: Relevance;
  customerInsightsRelevance?: Relevance;
  customerServiceRelevance?: Relevance;
  fieldServiceRelevance?: Relevance;
  contactCenterRelevance?: Relevance;
  bestFor?: string;               // "Passar bäst för"
  considerations?: string;        // "Tänk på"
  sourceUrl?: string;             // Källa (visas för redaktionen)
  verifiedAt?: string;            // Datum för senaste verifiering
  // Interna redaktionella fält – visas aldrig för besökare
  editorialTier?: string;
  nordicRelevance?: string;       // high | medium | low
  publicationWave?: string;       // now | wave_2
  sourceStatus?: string;          // Intern källstatus (Verifierad, Verifiera före publicering …)
  lifecycleStatus?: string;       // active | end_of_sale | discontinued (visas aldrig publikt)
}

/** Relevansvärdet för en enskild CE-applikation. */
export function ceRelevance(s: IsvSolution, app: CeApp): Relevance | undefined {
  switch (app) {
    case "Sales": return s.salesRelevance;
    case "Customer Insights (Marketing)": return s.customerInsightsRelevance;
    case "Customer Service": return s.customerServiceRelevance;
    case "Field Service": return s.fieldServiceRelevance;
    case "Contact Center": return s.contactCenterRelevance;
    default: return undefined;
  }
}

/** CE-applikationer där lösningen är relevant (ja eller delvis). */
export function ceApps(s: IsvSolution): CeApp[] {
  return CE_APPS.filter((a) => {
    const r = ceRelevance(s, a);
    return r === "yes" || r === "partial";
  });
}


